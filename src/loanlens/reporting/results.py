"""reports/results_summary.md (+ .json): the headline numbers, gathered from every step."""

from __future__ import annotations

import json

from loanlens.config import Settings
from loanlens.reporting.md import fmt_pct
from loanlens.warehouse import query


def _load(path):
    return json.loads(path.read_text()) if path.exists() else {}


def collect(settings: Settings) -> dict:
    art = settings.artifacts_dir
    pd_m = _load(art / "models" / "pd_metrics.json")
    stress = _load(art / "models" / "stress_summary.json")
    cut = _load(art / "decision" / "cutoff.json")
    fair = _load(art / "fairness" / "fairness_summary.json")
    surv = _load(art / "models" / "survival_summary.json")
    vol = query(settings, """select sum(orig_rows) as loans, sum(perf_rows) as records,
                                    count(*) as periods from meta.ingest_log l
                             where status = 'loaded' and finished_at = (
                                 select max(finished_at) from meta.ingest_log x
                                 where x.source_period = l.source_period and x.status = 'loaded')""").iloc[0]
    # checks behind the data now in the warehouse (runs that loaded), and batches the gates stopped
    dq = query(settings, """select count(*) as checks, avg(d.success::int) as pass_rate
                            from meta.dq_results d
                            join meta.ingest_log l on l.run_id = d.run_id and l.source_period = d.source_period
                            where l.status = 'loaded'""").iloc[0]
    blocked = query(settings, "select count(*) as n from meta.ingest_log where status = 'failed'").iloc[0]
    sev = next((r for r in stress.get("named", []) if r["scenario_id"] == "Severely adverse"), {})
    t = pd_m.get("test", {})
    return {
        "profile": settings.profile,
        "data": "synthetic (Freddie Mac layout, FRED-driven)" if settings["synthetic"] else "Freddie Mac loan-level",
        "loans": int(vol["loans"]), "monthly_records": int(vol["records"]), "source_periods": int(vol["periods"]),
        "dq_checks": int(dq["checks"]), "dq_pass_rate": float(dq["pass_rate"]),
        "dq_batches_blocked": int(blocked["n"]),
        "auc_xgboost": t.get("xgboost", {}).get("auc"), "auc_logistic": t.get("logistic_regression", {}).get("auc"),
        "auc_ci_xgboost": pd_m.get("auc_ci95", {}).get("xgboost"),
        "auc_ci_logistic": pd_m.get("auc_ci95", {}).get("logistic_regression"),
        "test_default_rate": t.get("xgboost", {}).get("base_rate"),
        "test_mean_pd": t.get("xgboost", {}).get("mean_pd"),
        "cox_concordance_default": surv.get("cox_default", {}).get("concordance"),
        "n_scenarios": stress.get("n_scenarios"), "horizon_months": stress.get("horizon_months"),
        "expected_loss_rate": stress.get("expected_loss_rate"), "var99_loss_rate": stress.get("var99_loss_rate"),
        "es99_loss_rate": stress.get("es99_loss_rate"), "severely_adverse_loss_rate": sev.get("loss_rate"),
        "backtest": stress.get("backtest", {}),
        "cutoff_pd": cut.get("cutoff_pd"), "profit_uplift": cut.get("test", {}).get("profit_uplift"),
        "approval_rate": cut.get("test", {}).get("approval_rate"),
        "defaults_avoided_share": cut.get("test", {}).get("defaults_avoided_share"),
        "fairness_min_air": fair.get("min_air_recommended"), "fairness_flags": len(fair.get("flags", [])),
    }


def write_results_summary(settings: Settings) -> dict:
    r = collect(settings)
    (settings.reports_dir / "results_summary.json").write_text(json.dumps(r, indent=2, default=float))
    bt = r["backtest"]
    text = f"""# Results summary

*Profile `{r['profile']}` - {r['data']}. Regenerated by `loanlens report`.*

| Result | Value |
|---|---|
| Loans processed | **{r['loans']:,}** ({r['loans'] / 1e6:.2f} million) |
| Monthly performance records | **{r['monthly_records']:,}** ({r['monthly_records'] / 1e6:.1f} million) across {r['source_periods']} source files |
| Data-quality checks | {r['dq_checks']:,} Great Expectations checks on the loaded data, {fmt_pct(r['dq_pass_rate'], 2)} passed; {r['dq_batches_blocked']} batch(es) stopped by the gates before load |
| Default model AUC (out-of-time) | **XGBoost {r['auc_xgboost']:.3f}** (95% CI {r['auc_ci_xgboost'][0]:.3f}-{r['auc_ci_xgboost'][1]:.3f}) vs **logistic regression {r['auc_logistic']:.3f}** ({r['auc_ci_logistic'][0]:.3f}-{r['auc_ci_logistic'][1]:.3f}) |
| Calibration (test vintages) | mean PD {fmt_pct(r['test_mean_pd'])} vs observed {fmt_pct(r['test_default_rate'])} |
| Cox model concordance (default) | {r['cox_concordance_default']:.3f} |
| Stress test | **{fmt_pct(r['var99_loss_rate'])}** 99th-percentile loss ({fmt_pct(r['es99_loss_rate'])} expected shortfall) across **{r['n_scenarios']:,}** scenarios over {r['horizon_months']} months; expected loss {fmt_pct(r['expected_loss_rate'])}; CCAR-style severely adverse {fmt_pct(r['severely_adverse_loss_rate'])} |
| Backtest 2008-2010 | projected vs actual defaults: {bt.get('in_sample_default_error', float('nan')) * 100:+.0f}% (all-history model), {bt.get('default_rate_error', float('nan')) * 100:+.0f}% (crisis excluded); naive benchmark {bt.get('naive_error', float('nan')) * 100:+.0f}% |
| Recommended approval cutoff | PD <= {fmt_pct(r['cutoff_pd'])}: approves {fmt_pct(r['approval_rate'], 1)}, avoids {fmt_pct(r['defaults_avoided_share'], 1)} of defaults, **{r['profit_uplift'] * 100:+.2f}%** projected profit (out-of-sample) |
| Fair-lending review | minimum adverse impact ratio {r['fairness_min_air']:.3f}; {r['fairness_flags']} flag(s) for review |

"""
    if settings["synthetic"]:
        text += """
These figures are produced from the **synthetic** dataset shipped with the repository and demonstrate the
pipeline; run the `freddie` profile on the real Freddie Mac files before quoting them as findings.
"""
    (settings.reports_dir / "results_summary.md").write_text(text)
    return r
